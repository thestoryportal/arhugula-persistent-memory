def write(root: Path, rel: str, text: str) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def snapshot(root: Path) -> dict:
    out = {}
    for dirpath, dirnames, filenames in os.walk(root):
        for name in dirnames + filenames:
            path = os.path.join(dirpath, name)
            st = os.lstat(path)
            data = b""
            if os.path.isfile(path) and not os.path.islink(path):
                with open(path, "rb") as fh:
                    data = fh.read()
            out[os.path.relpath(path, root)] = (st.st_mode, st.st_size, st.st_mtime_ns, data)
    return out


class Fixture(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="registry_match_"))
        self.addCleanup(shutil.rmtree, self.tmp, True)
        self.root = self.tmp / "repo"
        write(self.root, R.REGISTRY, REGISTRY)
        write(self.root, R.INDEX, INDEX)
        write(self.root, "experiments/c10l/CONTEXT.md", C10L_CONTEXT)
        write(self.root, "experiments/legacy_dir/CONTEXT.md", LEGACY_DIR_CONTEXT)
        write(self.root, "experiments/stage_2_sweep/CONTEXT.md", STAGE2_DIR_CONTEXT)
        write(self.root, "experiments/CONTEXT.md", "# experiments\n\nstage_2_sweep is not here.\n")
        # Run folders on disk are not a source: only the three named sources decide.
        (self.root / "experiments/c10r/runs/autoresearch_c10_equivalence_run").mkdir(parents=True)
        (self.root / "experiments/t3/runs/s229_t3_mistral_memit").mkdir(parents=True)

    def match(self, unit: str) -> R.Match:
        return R.match_unit(self.root, unit)

    def run_cli(self, *args: str) -> subprocess.CompletedProcess:
        return subprocess.run(
            [sys.executable, "-B", str(TOOL), *args],
            capture_output=True, text=True, timeout=60, check=False,
        )


class Controls(Fixture):
    def test_autoresearch_family_gives_c10r(self):
        m = self.match("autoresearch_*")
        self.assertEqual(m.result, "exact")
        self.assertEqual(m.experiment_id, "c10r")
        self.assertEqual(m.candidates, ("c10r",))
        self.assertEqual(
            [(e.source, e.line, e.experiment_ids) for e in m.evidence],
            [(R.REGISTRY, 5, ("c10r",))],
        )
        self.assertIn("autoresearch_c10_equivalence_run", m.evidence[0].text)

    def test_stage_2_sweep_gives_none(self):
        m = self.match("stage_2_sweep")
        self.assertEqual(m.result, "none")
        self.assertIsNone(m.experiment_id)
        self.assertEqual(m.candidates, ())
        # Exact tokens only: stage_2_sweep_trials and stage_2_sweep_design.md are other names.
        # The experiments/stage_2_sweep folder has no ID, so its mentions name no experiment.
        self.assertEqual(
            [(e.source, e.line, e.experiment_ids) for e in m.evidence],
            [
                ("experiments/stage_2_sweep/CONTEXT.md", 1, ()),
                ("experiments/stage_2_sweep/CONTEXT.md", 3, ()),
            ],
        )

    def test_exact_name_from_context_runs(self):
        m = self.match("c10l_mint")
        self.assertEqual((m.result, m.experiment_id), ("exact", "c10l"))
        self.assertEqual(
            [(e.source, e.line, e.experiment_ids) for e in m.evidence],
            [("experiments/c10l/CONTEXT.md", 5, ("c10l",))],
        )


