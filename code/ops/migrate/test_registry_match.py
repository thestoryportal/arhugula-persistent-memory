class ReadOnlyCli(Fixture):
    def test_cli_reports_and_writes_nothing(self):
        before = snapshot(self.tmp)
        proc = self.run_cli("--root", str(self.root), "--unit", "autoresearch_*", "--unit", "stage_2_sweep")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertEqual(snapshot(self.tmp), before)
        doc = json.loads(proc.stdout)
        got = [(m["unit"], m["result"], m["experiment_id"]) for m in doc["matches"]]
        self.assertEqual(got, [("autoresearch_*", "exact", "c10r"), ("stage_2_sweep", "none", None)])
        ev = doc["matches"][0]["evidence"][0]
        self.assertEqual((ev["source"], ev["line"]), (R.REGISTRY, 5))

    def test_cli_requires_root(self):
        proc = self.run_cli("--unit", "stage_2_sweep")
        self.assertEqual(proc.returncode, 2)
        self.assertEqual(proc.stdout, "")


class Refusals(Fixture):
    def assert_refused(self, *args: str) -> str:
        before = snapshot(self.tmp)
        proc = self.run_cli("--root", str(self.root), *args)
        self.assertEqual(proc.returncode, 2, proc.stdout + proc.stderr)
        self.assertEqual(proc.stdout, "")
        self.assertEqual(snapshot(self.tmp), before)
        return proc.stderr

    def test_missing_registry_refuses(self):
        os.rename(self.root / R.REGISTRY, self.tmp / "moved.md")
        self.assertIn("EXPERIMENT_REGISTRY.md", self.assert_refused("--unit", "stage_2_sweep"))
        with self.assertRaises(R.Refusal):
            self.match("stage_2_sweep")

    def test_missing_index_refuses(self):
        os.rename(self.root / R.INDEX, self.tmp / "moved.md")
        self.assertIn("experiments.md", self.assert_refused("--unit", "stage_2_sweep"))

    def test_symlinked_registry_out_of_root_refuses(self):
        outside = self.tmp / "outside.md"
        outside.write_text(REGISTRY, encoding="utf-8")
        os.remove(self.root / R.REGISTRY)
        os.symlink(outside, self.root / R.REGISTRY)
        self.assertIn("link", self.assert_refused("--unit", "autoresearch_*"))

    def test_symlinked_experiment_folder_refuses(self):
        other = self.tmp / "other"
        write(other, "CONTEXT.md", "---\nid: evil\n---\nautoresearch_x\n")
        os.symlink(other, self.root / "experiments/evil")
        self.assertIn("link", self.assert_refused("--unit", "autoresearch_*"))

    def test_symlinked_context_file_refuses(self):
        outside = self.tmp / "ctx.md"
        outside.write_text("---\nid: evil\n---\n", encoding="utf-8")
        os.makedirs(self.root / "experiments/linked")
        os.symlink(outside, self.root / "experiments/linked/CONTEXT.md")
        self.assertIn("link", self.assert_refused("--unit", "autoresearch_*"))

    def test_malformed_frontmatter_id_refuses(self):
        write(self.root, "experiments/bad/CONTEXT.md", "---\nid: two words\n---\n")
        self.assertIn("id", self.assert_refused("--unit", "autoresearch_*"))

    def test_path_or_blank_unit_refuses(self):
        for unit in ("/Volumes/memit/stage_2_sweep", "stage 2", "", "a/b"):
            with self.subTest(unit=unit):
                self.assert_refused("--unit", unit)
                with self.assertRaises(R.Refusal):
                    self.match(unit)

    def test_non_utf8_source_refuses(self):
        (self.root / R.INDEX).write_bytes(b"| id |\n| \xff |\n")
        self.assertIn("UTF-8", self.assert_refused("--unit", "autoresearch_*"))


