#!/usr/bin/env python3
"""Render the program state views from program/program_state.json.

Usage from the repo root:
  LLMDB_ROOT=$PWD python3 -B code/state/render_state.py --write
  LLMDB_ROOT=$PWD python3 -B code/state/render_state.py --check
The default mode is --check. Missing or stale views give exit 1.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import sys

ROOT = Path(os.environ.get("LLMDB_ROOT") or Path(__file__).resolve().parents[2])
STATE = ROOT / "program/program_state.json"
TARGETS = [("program/STATUS.md", "status"),
           ("_index/program-state.md", "program-state"),
           ("program/scorecard.md", "f1-scorecard")]
STATUS_LIMIT = 11000
ACTION_LIMIT = 16
QUEUE_LIMIT = 16
EDIT_NOTE = "_Generated from `program/program_state.json`. Do not edit this file. Run `LLMDB_ROOT=$PWD PYTHONPATH=code /Volumes/memit/llm-database-poc-mirror/arhugula-persistent-memory/.venv/bin/python -B code/state/render_state.py --write` from the repo root._"


def _state():
    raw = STATE.read_bytes()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def summary(text, limit):
    text = re.sub(r"\s+", " ", text).strip()
    raw = text.encode("utf-8")
    return text if len(raw) <= limit else raw[:limit - 4].decode("utf-8", errors="ignore") + " …"


def open_queue(s):
    return [q for q in s.get("work_queue", {}).get("items", [])
            if q["state"] not in ("done", "cancelled")]


def with_overflow(lines, total):
    text = "\n".join(lines)
    if total > len(lines):
        text += f"\n{total - len(lines)} more: see `_index/program-state.md`"
    return text


def render_status(s):
    actions = with_overflow([f"{i + 1}. {summary(a, 240)}"
                             for i, a in enumerate(s["next_actions"][:ACTION_LIMIT])],
                            len(s["next_actions"]))
    items = open_queue(s)
    queue = with_overflow([
        summary(f"- **{summary(q['id'], 64)}** ({summary(q['state'], 24)}): "
                f"{summary(q['title'], 120)}. {summary(q.get('summary', ''), 140)}", 200)
        for q in items[:QUEUE_LIMIT]], len(items))
    text = ("# Program status\n\n"
            "Summaries can be shortened. Read the [full state](../_index/program-state.md) "
            "and the [source](program_state.json) for complete text.\n\n"
            f"Updated: {summary(s['updated'].split(' ', 1)[0], 32)}\n\n"
            f"## North star\n\n{summary(s['north_star'], 384)}\n\n"
            f"## Current position\n\n{summary(s['current_latest'], 1200)}\n\n"
            f"F1 status: {summary(s['f1_verdict'], 1100)}\n\n"
            f"## Next actions\n\n{actions}\n\n"
            f"## Open work queue\n\n{queue or 'No open items.'}\n")
    return text


def render(block, s):
    if block == "program-state":
        acts = "\n".join(f"  {i+1}. {a}" for i, a in enumerate(s["next_actions"]))
        return (f"**📍 PROGRAM STATE (updated {s['updated']})** — {EDIT_NOTE}\n\n"
                f"- **North star:** {s['north_star']}\n"
                f"- **Latest:** {s['current_latest']}\n"
                f"- **F1 status:** {s['f1_verdict']}\n"
                f"- **Next actions (priority):**\n{acts}")
    if block == "f1-scorecard":
        sc = s["scorecard"]
        return (f"**F1 READINESS SCORECARD (updated {s['updated']})** — {EDIT_NOTE}\n\n"
                f"- **Deployment data path:** {sc['deployment_path']}\n"
                f"- **Governance:** {sc['governance']}\n"
                f"- **Robustness:** {sc['robustness']}\n"
                f"- **Critical path:** {sc['critical_path']}\n"
                f"- **Verdict:** {s['f1_verdict']}")
    raise KeyError(block)



def view(block, s, source_sha256):
    header = f"{EDIT_NOTE}\n_Source SHA256: `{source_sha256}`._\n\n"
    if block == "status":
        text = header + render_status(s)
        size = len(text.encode("utf-8"))
        if size > STATUS_LIMIT:
            raise ValueError(f"program/STATUS.md needs {size} bytes; limit is {STATUS_LIMIT}. "
                             "Reduce the summaries before writing the views.")
        return text
    text = (f"{header}<!-- BEGIN GENERATED:{block} -->\n"
            f"{render(block, s)}\n<!-- END GENERATED:{block} -->\n")
    if block == "program-state":
        queue = "\n".join(f"- **{q['id']}** ({q['state']}): {q['title']}. {q.get('summary', '')}"
                          for q in open_queue(s))
        text += f"\n## Open work queue\n\n{queue or 'No open items.'}\n"
    return text


def apply(path, content, write):
    full = ROOT / path
    stale = not full.is_file() or full.read_bytes() != content.encode("utf-8")
    if stale and write:
        full.parent.mkdir(parents=True, exist_ok=True)
        full.write_bytes(content.encode("utf-8"))
    return stale


def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if mode not in ("--check", "--write"):
        print(__doc__)
        sys.exit(2)
    s, source_sha256 = _state()
    try:
        views = [(path, view(block, s, source_sha256)) for path, block in TARGETS]
    except ValueError as err:
        print(f"❌ render error: {err}")
        sys.exit(2)
    stale = []
    for path, content in views:
        changed = apply(path, content, write=(mode == "--write"))
        tag = "WROTE " if changed and mode == "--write" else "STALE " if changed else "ok    "
        print(f"  [{tag}] {path}")
        if changed and mode == "--check":
            stale.append(path)
    if stale:
        print(f"❌ {len(stale)} stale or missing generated view(s): {stale}. {EDIT_NOTE}")
        sys.exit(1)
    print("✅ generated views WRITTEN." if mode == "--write" else "✅ all generated views current.")
    sys.exit(0)


if __name__ == "__main__":
    main()
