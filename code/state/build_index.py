"""Build deterministic ICM indexes and the LabViz map. Generation never writes a sealed map."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import subprocess

import yaml

if __package__:
    from .llmdb_records import project_rows
    from .resolve_path import build_anchor_map, read_anchor_map, read_path_map, relocate
else:
    from llmdb_records import project_rows
    from resolve_path import build_anchor_map, read_anchor_map, read_path_map, relocate

STATUSES = {'designed', 'frozen', 'running', 'halted', 'verdict', 'deferred'}
MIN_MAP_ROWS = 31820
SEALED_MAP = '_index/path-map.tsv'
RELOCATIONS = '_index/icm21-path-map.tsv'
LABVIZ_APP = 'code/apps/labviz'
LABVIZ_MAP = LABVIZ_APP + '/results_moves.json'
LABVIZ_ABOUT = 'Derived from sealed path map and approved ICM v2.1 relocations.'


def cell(value):
    if value is None or value == '' or value == []:
        return '—'
    if isinstance(value, list):
        return ', '.join(cell(item) for item in value)
    return str(value).replace('|', '\\|').replace('\r', ' ').replace('\n', ' ')


def table(title, headers, rows, note=''):
    lines = [f'# {title}', '', 'Generated by code/state/build_index.py.', '']
    if note:
        lines.extend([note, ''])
    lines.extend(['| ' + ' | '.join(headers) + ' |',
                  '| ' + ' | '.join('---' for _ in headers) + ' |'])
    lines.extend('| ' + ' | '.join(cell(v) for v in row) + ' |' for row in rows)
    return ('\n'.join(lines) + '\n').encode('utf-8')


def first_heading(path):
    fenced = False
    previous = ''
    text = path.read_text(encoding='utf-8')
    text = re.sub(r'\A---[ \t]*\n.*?\n---[ \t]*(?:\n|$)', '', text, count=1, flags=re.S)
    for line in text.splitlines():
        if line.lstrip().startswith(('```', '~~~')):
            fenced = not fenced
        if not fenced:
            match = re.match(r'^ {0,3}#{1,6}\s+(.+?)\s*#*\s*$', line)
            if match:
                return match.group(1)
            if previous.strip() and re.fullmatch(r' {0,3}(?:=+|-+)\s*', line):
                return previous.strip()
        previous = '' if fenced else line
    return None


def checkout_folders(root: Path) -> set[str]:
    # rows come from what git carries (tracked, or new and not ignored), so a fresh checkout and
    # a working tree with empty folders or ignored debris give the same index
    listing = subprocess.run(['git', '-C', str(root), 'ls-files', '-z', '--cached', '--others',
                              '--exclude-standard'], capture_output=True, check=True).stdout
    return {'/'.join(path.split('/')[:2]) for path in listing.decode().split('\0')
            if path.count('/') >= 2}


def generate(root: Path) -> dict[str, bytes]:
    present = checkout_folders(root)
    experiments = []
    unstamped = 0
    for folder in sorted((root / 'experiments').iterdir()):
        if f'experiments/{folder.name}' not in present:
            continue
        path = folder / 'CONTEXT.md'
        if not path.exists():
            unstamped += 1
            experiments.append([folder.name, None, None, None, None, None])
            continue
        text = path.read_text(encoding='utf-8')
        match = re.match(r'\A---\s*\n(.*?)\n---\s*(?:\n|$)', text, re.S)
        if not match:
            raise ValueError(f'{path.relative_to(root)}: missing YAML frontmatter')
        try:
            record = yaml.safe_load(match.group(1))
        except yaml.YAMLError as error:
            raise ValueError(f'{path.relative_to(root)}: invalid YAML: {error}') from error
        if not isinstance(record, dict):
            raise ValueError(f'{path.relative_to(root)}: frontmatter must be a mapping')
        status = record.get('status')
        if not isinstance(status, str) or status not in STATUSES:
            raise ValueError(f'{path.relative_to(root)}: invalid status {status!r}')
        experiments.append([folder.name] + [record.get(key) for key in
                            ('family', 'title', 'status', 'corpus', 'decision_ids')])

    state = json.loads((root / 'program/program_state.json').read_text(encoding='utf-8'))
    folders = {p.name for p in (root / 'projects').iterdir() if f'projects/{p.name}' in present}
    projects = project_rows(state['work_queue']['items'], folders, root)
    evidence = [[p.name, first_heading(p)] for p in sorted((root / 'evidence/CORPUS').iterdir())
                if p.is_file() and p.name != 'CONTEXT.md']
    checkpoints = [[p.name, first_heading(p)] for p in sorted(
        (root / 'program/checkpoints').iterdir(),
        key=lambda p: (int(p.name.split('-', 1)[0]) if re.match(r'^\d+-', p.name)
                       else float('inf'), p.name)) if p.is_file() and p.name != 'CONTEXT.md']
    newest = next(('program/checkpoints/' + name for name, heading in checkpoints
                   if heading and 'live handoff' in heading.lower()), '—')
    return {
        'experiments.md': table('Experiments', ['id', 'family', 'title', 'status', 'corpus',
                                               'decision_ids'], experiments, f'Unstamped: {unstamped}'),
        'projects.md': table('Projects', ['id', 'title', 'state', 'relation', 'kind',
                                            'path'], projects),
        'evidence.md': table('Evidence', ['file', 'first heading'], evidence),
        'checkpoints.md': table('Checkpoints', ['file', 'first heading'], checkpoints,
                                f'Newest live handoff: {newest}'),
    }


def read_input(root: Path, relative: str) -> bytes:
    """Read a fixed map input beneath root, refusing any symlink component below root."""
    path = root
    for part in Path(relative).parts:
        path = path / part
        if path.is_symlink():
            raise ValueError(f'{relative}: symlink component {path.relative_to(root)}')
    if not path.is_file():
        raise ValueError(f'{relative}: missing input')
    return path.read_bytes()


def read_relocations(data: bytes) -> dict[str, str]:
    try:
        relocations = read_path_map(data)
    except ValueError as error:
        raise ValueError(f'{RELOCATIONS}: {error}') from error
    for old, new in relocations.items():
        if old == new:
            raise ValueError(f'{RELOCATIONS}: identity relocation {old}')
    return relocations


def labviz_map(sealed: bytes, relocations: bytes) -> bytes:
    """LabvizMoves: every sealed results/ key at its final path, bound to both complete inputs."""
    moves = read_relocations(relocations)
    data = {
        'about': LABVIZ_ABOUT,
        'derived_from': {key: {'path': name, 'sha256': hashlib.sha256(raw).hexdigest()}
                         for key, name, raw in (('sealed', SEALED_MAP, sealed),
                                                ('relocations', RELOCATIONS, relocations))},
        'moves': {old: relocate(new, moves) for old, new in read_path_map(sealed).items()
                  if old.startswith('results/')},
    }
    return json.dumps(data, sort_keys=True, separators=(',', ':')).encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    parser.add_argument('--labviz-map-only', action='store_true',
                        help='generate or check only ' + LABVIZ_MAP)
    parser.add_argument('--path-map', type=Path,
                        help='install this sealed path map and rebuild its anchor map')
    args = parser.parse_args()
    if args.path_map and (args.check or args.labviz_map_only):
        parser.error('--path-map requires --write without --labviz-map-only')
    try:
        root = Path(os.environ['LLMDB_ROOT'])
        index = root / '_index'
        map_data = args.path_map.read_bytes() if args.path_map else read_input(root, SEALED_MAP)
        # A root that holds LabViz binds the sealed map by digest in LABVIZ_MAP;
        # elsewhere the row floor is the only guard against a truncated map.
        with_labviz = args.labviz_map_only or (root / LABVIZ_APP).is_dir()
        read_path_map(map_data, 0 if with_labviz else MIN_MAP_ROWS)
        expected = {} if args.labviz_map_only else {
            '_index/' + name: data for name, data in generate(root).items()}
        if with_labviz:
            expected[LABVIZ_MAP] = labviz_map(map_data, read_input(root, RELOCATIONS))
        if args.write:
            if args.path_map:
                anchor_data = build_anchor_map(root, read_path_map(map_data, MIN_MAP_ROWS))
                index.mkdir(exist_ok=True)
                (index / 'path-map.tsv').write_bytes(map_data)
                print('Copied _index/path-map.tsv', flush=True)
                (index / 'anchor-map.tsv').write_bytes(anchor_data)
                print('Wrote _index/anchor-map.tsv', flush=True)
            for name, data in expected.items():
                (root / name).parent.mkdir(parents=True, exist_ok=True)
                (root / name).write_bytes(data)
                print(f'Wrote {name}', flush=True)
            return 0
        if not args.labviz_map_only:
            read_anchor_map((index / 'anchor-map.tsv').read_bytes(), root)
        drift = [name for name, data in expected.items()
                 if not (root / name).is_file() or (root / name).read_bytes() != data]
        for name in drift:
            print(f'Drift: {name}', flush=True)
        if not drift:
            print('INDEX CLEAN', flush=True)
        return int(bool(drift))
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f'Error: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
