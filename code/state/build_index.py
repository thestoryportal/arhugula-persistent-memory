"""Build deterministic ICM indexes. The approved path map stays byte-identical."""
import argparse
import csv
import io
import json
import os
from pathlib import Path
import re
import sys
import subprocess

import yaml

STATUSES = {'designed', 'frozen', 'running', 'halted', 'verdict', 'deferred'}
MAP_HEADER = ['old', 'new', 'disposition', 'unit']
MIN_MAP_ROWS = 31820


def read_path_map(data: bytes, minimum: int = 0) -> dict[str, str]:
    if data.splitlines()[:1] != [b'old\tnew\tdisposition\tunit']:
        raise ValueError('_index/path-map.tsv: expected exact header old\tnew\tdisposition\tunit')
    rows = csv.reader(io.StringIO(data.decode('utf-8')), delimiter='\t')
    if next(rows, None) != MAP_HEADER:
        raise ValueError('_index/path-map.tsv: expected header old\tnew\tdisposition\tunit')
    result = {}
    for number, row in enumerate(rows, 2):
        if len(row) != 4 or not row[0]:
            raise ValueError(f'_index/path-map.tsv: malformed row {number}')
        if row[0] in result:
            raise ValueError(f'_index/path-map.tsv: repeated old path {row[0]}')
        result[row[0]] = row[1]
    if len(result) < minimum:
        raise ValueError(f'_index/path-map.tsv: {len(result)} rows; need at least {minimum}')
    return result


def cell(value):
    if value is None or value == '' or value == []:
        return '—'
    if isinstance(value, list):
        return ', '.join(cell(item) for item in value)
    return str(value).replace('|', '\\|').replace('\r', ' ').replace('\n', ' ')


def table(title, headers, rows, note=''):
    lines = [f'# {title}', '', 'Generated by code/state/build_index.py.', '']
    if note:
        lines.extend([note, ''])
    lines.extend(['| ' + ' | '.join(headers) + ' |',
                  '| ' + ' | '.join('---' for _ in headers) + ' |'])
    lines.extend('| ' + ' | '.join(cell(v) for v in row) + ' |' for row in rows)
    return ('\n'.join(lines) + '\n').encode('utf-8')


def first_heading(path):
    fenced = False
    previous = ''
    text = path.read_text(encoding='utf-8')
    text = re.sub(r'\A---[ \t]*\n.*?\n---[ \t]*(?:\n|$)', '', text, count=1, flags=re.S)
    for line in text.splitlines():
        if line.lstrip().startswith(('```', '~~~')):
            fenced = not fenced
        if not fenced:
            match = re.match(r'^ {0,3}#{1,6}\s+(.+?)\s*#*\s*$', line)
            if match:
                return match.group(1)
            if previous.strip() and re.fullmatch(r' {0,3}(?:=+|-+)\s*', line):
                return previous.strip()
        previous = '' if fenced else line
    return None


def generate(root: Path) -> dict[str, bytes]:
    experiments = []
    unstamped = 0
    for folder in sorted((root / 'experiments').iterdir()):
        if not folder.is_dir():
            continue
        path = folder / 'CONTEXT.md'
        if not path.exists():
            unstamped += 1
            experiments.append([folder.name, None, None, None, None, None])
            continue
        text = path.read_text(encoding='utf-8')
        match = re.match(r'\A---\s*\n(.*?)\n---\s*(?:\n|$)', text, re.S)
        if not match:
            raise ValueError(f'{path.relative_to(root)}: missing YAML frontmatter')
        try:
            record = yaml.safe_load(match.group(1))
        except yaml.YAMLError as error:
            raise ValueError(f'{path.relative_to(root)}: invalid YAML: {error}') from error
        if not isinstance(record, dict):
            raise ValueError(f'{path.relative_to(root)}: frontmatter must be a mapping')
        status = record.get('status')
        if not isinstance(status, str) or status not in STATUSES:
            raise ValueError(f'{path.relative_to(root)}: invalid status {status!r}')
        experiments.append([folder.name] + [record.get(key) for key in
                            ('family', 'title', 'status', 'corpus', 'decision_ids')])

    state = json.loads((root / 'program/program_state.json').read_text(encoding='utf-8'))
    queue = {}
    for item in state['work_queue']['items']:
        if item['id'] in queue:
            raise ValueError(f'program/program_state.json: repeated queue id {item["id"]}')
        queue[item['id']] = item
    folders = {p.name for p in (root / 'projects').iterdir() if p.is_dir()}
    open_ids = {key for key, item in queue.items()
                if str(item['state']).lower() not in {'done', 'closed', 'cancelled', 'canceled'}}
    projects = []
    for key in sorted(folders | open_ids):
        item = queue.get(key, {})
        relation = 'folder and queue item' if key in folders and key in queue else (
            'no queue item' if key in folders else 'no folder')
        projects.append([key, item.get('title'), item.get('state'), relation])
    evidence = [[p.name, first_heading(p)] for p in sorted((root / 'evidence/CORPUS').iterdir())
                if p.is_file()]
    checkpoints = [[p.name, first_heading(p)] for p in sorted(
        (root / 'program/checkpoints').iterdir(),
        key=lambda p: (int(p.name.split('-', 1)[0]) if re.match(r'^\d+-', p.name)
                       else float('inf'), p.name)) if p.is_file()]
    newest = next(('program/checkpoints/' + name for name, heading in checkpoints
                   if heading and 'live handoff' in heading.lower()), '—')
    return {
        'experiments.md': table('Experiments', ['id', 'family', 'title', 'status', 'corpus',
                                               'decision_ids'], experiments, f'Unstamped: {unstamped}'),
        'projects.md': table('Projects', ['id', 'title', 'state', 'relation'], projects),
        'evidence.md': table('Evidence', ['file', 'first heading'], evidence),
        'checkpoints.md': table('Checkpoints', ['file', 'first heading'], checkpoints,
                                f'Newest live handoff: {newest}'),
    }


def read_anchor_map(data: bytes, root: Path) -> dict[tuple[str, str], str]:
    if data.splitlines()[:1] != [b'monolith\tanchor\tpart']:
        raise ValueError('_index/anchor-map.tsv: expected exact header monolith\tanchor\tpart')
    rows = csv.reader(io.StringIO(data.decode('utf-8')), delimiter='\t')
    next(rows)
    result = {}
    for number, row in enumerate(rows, 2):
        if len(row) != 3 or not all(row):
            raise ValueError(f'_index/anchor-map.tsv: malformed row {number}')
        monolith, anchor, part = row
        key = (monolith, anchor)
        if key in result:
            raise ValueError(f'_index/anchor-map.tsv: repeated anchor {monolith}#{anchor}')
        path = Path(part)
        if path.is_absolute() or '..' in path.parts or not (root / path).is_file():
            raise ValueError(f'_index/anchor-map.tsv: missing or invalid part {part}')
        result[key] = part
    return result


def build_anchor_map(root: Path, mapping: dict[str, str]) -> bytes:
    if __package__:
        from .resolve_path import SPLITS, heading_entries
    else:
        from resolve_path import SPLITS, heading_entries
    rows = []
    for old, monolith in sorted(mapping.items()):
        if monolith not in SPLITS:
            continue
        folder = SPLITS[monolith]
        parts = sorted((root / folder).glob('[0-9]*.md'))
        source = subprocess.run(['git', 'show', f'3f1a3b95:{old}'], cwd=root,
                                capture_output=True, text=True)
        if source.returncode or not source.stdout:
            raise ValueError(f'_index/anchor-map.tsv: cannot read 3f1a3b95:{old}: '
                             + source.stderr.strip())
        entries = list(heading_entries(source.stdout.splitlines()))
        # All three lossless splits start each part at a level-two heading.
        boundaries = sum(bool(re.match(r'^ {0,3}##\s+', heading))
                         for heading, slug in entries)
        if not parts or boundaries != len(parts):
            raise ValueError(f'_index/anchor-map.tsv: {old}: {boundaries} section '
                             f'boundaries do not match {len(parts)} parts')
        position = -1
        for heading, slug in entries:
            if re.match(r'^ {0,3}##\s+', heading):
                position += 1
            part = parts[max(position, 0)].relative_to(root).as_posix()
            rows.append((monolith, slug, part))
    data = ('monolith\tanchor\tpart\n' + ''.join(
        '\t'.join(row) + '\n' for row in sorted(rows))).encode('utf-8')
    read_anchor_map(data, root)
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    parser.add_argument('--path-map', type=Path)
    args = parser.parse_args()
    if args.check and args.path_map:
        parser.error('--path-map requires --write')
    try:
        root = Path(os.environ['LLMDB_ROOT'])
        expected = generate(root)
        index = root / '_index'
        map_data = (args.path_map or index / 'path-map.tsv').read_bytes()
        mapping = read_path_map(map_data, MIN_MAP_ROWS)
        if args.write:
            anchor_data = build_anchor_map(root, mapping)
            index.mkdir(exist_ok=True)
            for name, data in expected.items():
                (index / name).write_bytes(data)
                print(f'Wrote _index/{name}')
            if args.path_map:
                (index / 'path-map.tsv').write_bytes(map_data)
                print('Copied _index/path-map.tsv')
            (index / 'anchor-map.tsv').write_bytes(anchor_data)
            print('Wrote _index/anchor-map.tsv')
            return 0
        read_anchor_map((index / 'anchor-map.tsv').read_bytes(), root)
        drift = [name for name, data in expected.items()
                 if not (index / name).exists() or (index / name).read_bytes() != data]
        for name in drift:
            print(f'Drift: _index/{name}')
        if not drift:
            print('INDEX CLEAN')
        return int(bool(drift))
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f'Error: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
